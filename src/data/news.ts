export const NEWS_DATA: NewsItem[] = NEWS.map((n, i) => ({
  ...n,
  id: `news-${i + 1}`,
}));

export function getAllCategory(): string[] {
  return [...new Set(NEWS_DATA.map((item) => item.category))];
}

export function getNewsById(id: string): NewsItem | undefined {
  return NEWS_DATA.find((news) => news.id === id);
}

export function getNewsByCategory(category: string): NewsItem[] {
  if (category === "all") return NEWS_DATA;
  return NEWS_DATA.filter((news) => news.category === category);
}

export function getRandomNews(
  count: number,
  usedNewsIds: string[] = [],
  filterFunc?: (news: NewsItem) => boolean,
): NewsItem[] {
  const availableNews = NEWS_DATA.filter(
    (news) =>
      !usedNewsIds.includes(news.id) && (!filterFunc || filterFunc(news)),
  );

  if (availableNews.length <= count) {
    return availableNews;
  }

  // Перемешиваем массив
  const shuffled = [...availableNews].sort(() => Math.random() - 0.5);

  // Возвращаем первые count элементов
  return shuffled.slice(0, count);
}
